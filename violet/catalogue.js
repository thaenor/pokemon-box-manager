// Base-game Paldea Pokédex order from PokéAPI's pokemon_dex_numbers.csv (Pokédex 31).
// Species, types and common evolution thresholds from Pokémon Showdown's pokedex.json.
// Violet-specific conditions: serebii.net/scarletviolet/evolution.shtml and
// Bulbapedia's "List of methods of Evolution by index number in Generation IX".
// Methods deliberately contain no destination name or artwork. Identical triggers share a row.

function solo(title, detail) {
  return { kind: "Solo", title, detail };
}

function counted(label, goal, title, detail) {
  return { ...solo(title, detail), counter: { label, goal } };
}

function level(minimum, condition = "", detail = "") {
  const title = `Level up to Lv. ${minimum} or higher${condition ? " " + condition : ""}`;
  return solo(
    title,
    detail || "Gain a level in a regular battle or with a candy once the requirement is met.",
  );
}

function friendship(when = "") {
  return solo(
    "Level up with high friendship" + (when ? " " + when : ""),
    "Walk together and wash your Pokémon at picnics. The woman beside the fountain in Cascarrafa can check your friendship.",
  );
}

