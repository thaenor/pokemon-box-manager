#!/usr/bin/env node
/**
 * Regenerate the offline Champions roster with node scripts/build-roster.js.
 * Requires the live Champions Battle Data rankings and Pokémon Showdown Pokédex.
 */
import { writeFile } from "node:fs/promises";
import { createRankedSpecies, fetchRankings, fetchShowdownPokedex } from "../js/api/champions.js";

const [doubles, singles, pokedex] = await Promise.all([
  fetchRankings("Doubles"),
  fetchRankings("Singles"),
  fetchShowdownPokedex(),
]);
const rankedForms = new Map([...doubles, ...singles].map((row) => [row.showdownId, row]));
function getSpecies(row) {
  const entry = createRankedSpecies(row, pokedex);
  if (!entry) throw new Error(`Missing Pokémon Showdown metadata for ${row.showdownId}`);
  return entry;
}

// Keep the three Z Mega forms already supported by the box manager.
const zMegas = ["Absol", "Garchomp", "Lucario"].map((name) => {
  const id = name.toLowerCase();
  const slug = `${id}-mega-z`;
  return {
    ...getSpecies({ showdownId: `${id}megaz`, slug }),
    name: `Mega ${name} Z`,
    showdownId: `${id}-ultra`,
    pokeApiName: slug,
    isUltra: true,
  };
});

const entries = [...[...rankedForms.values()].map(getSpecies), ...zMegas].sort(
  (a, b) => a.id - b.id || a.name.localeCompare(b.name),
);
const output = `// Auto-generated by scripts/build-roster.js — do not edit manually
// Source: Pokémon Champions Battle Data rankings (${rankedForms.size} entries) and Pokémon Showdown
export const speciesList = ${JSON.stringify(entries, null, 2)};

export function findSpecies(name) {
  const search = name.toLowerCase().trim();
  return speciesList.find(
    (species) => species.showdownId.toLowerCase() === search || species.name.toLowerCase() === search,
  );
}
`;
await writeFile(new URL("../js/data/species-list.js", import.meta.url), output);
console.log(`Wrote ${entries.length} entries to js/data/species-list.js`);
